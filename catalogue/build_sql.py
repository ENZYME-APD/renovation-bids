"""Generate SQL from es_catalogue.py.

  python catalogue/build_sql.py
    -> supabase/migrations/20261020090000_catalogue_es_v1.sql   (shared Spain catalogue + templates)
    -> catalogue/out/enzyme_prices.sql                           (Enzyme's own prices; run once per studio)
"""
from pathlib import Path

import es_catalogue as C

ROOT = Path(__file__).resolve().parent.parent
MIGRATION = ROOT / "supabase" / "migrations" / "20261020090000_catalogue_es_v1.sql"
PRICES = Path(__file__).parent / "out" / "enzyme_prices.sql"


def q(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


SCHEMA = """\
-- Enzyme standard catalogue for Spain (v1), room templates, and the bid-stage rule.
-- Generated by catalogue/build_sql.py from catalogue/es_catalogue.py — edit there.

-- ── Chapters: code + CYPE chapter on trades; retire the placeholder seed ──────
alter table public.trades add column code text;
alter table public.trades add column cype_chapter text;
alter table public.trades add column active boolean not null default true;
create unique index trades_code_key on public.trades (region_id, organization_id, code) nulls not distinct
  where code is not null;

update public.trades set active = false, name = name || ' (v0)'
 where region_id = 'es' and organization_id is null and code is null;
update public.partidas set active = false
 where region_id = 'es' and organization_id is null and code like 'ES-%';

-- ── Room templates ───────────────────────────────────────────────────────────
create table public.room_templates (
  id               uuid primary key default gen_random_uuid(),
  region_id        text not null references public.regions (id),
  organization_id  uuid references public.organizations (id) on delete cascade,
  code             text not null,
  name             text not null,
  size_label       text not null default 'm² de suelo',
  description      text,
  sequence         smallint not null default 0,
  active           boolean not null default true,
  created_at       timestamptz not null default now(),
  unique nulls not distinct (region_id, organization_id, code)
);
create index room_templates_organization_id_idx on public.room_templates (organization_id);

create table public.room_template_lines (
  id           uuid primary key default gen_random_uuid(),
  template_id  uuid not null references public.room_templates (id) on delete cascade,
  partida_id   uuid not null references public.partidas (id),
  factor       numeric(10, 4) not null default 0,   -- quantity per unit of size
  fixed        numeric(10, 3) not null default 0,   -- quantity per room
  note         text,
  sequence     smallint not null default 0,
  unique (template_id, partida_id)
);
create index room_template_lines_partida_id_idx on public.room_template_lines (partida_id);

alter table public.room_templates enable row level security;
create policy room_templates_read on public.room_templates for select to authenticated
  using (organization_id is null or organization_id in (select private.user_org_ids()));
create policy room_templates_insert_own on public.room_templates for insert to authenticated
  with check (organization_id in (select private.user_org_ids()));
create policy room_templates_update_own on public.room_templates for update to authenticated
  using (organization_id in (select private.user_org_ids()))
  with check (organization_id in (select private.user_org_ids()));
create policy room_templates_delete_own on public.room_templates for delete to authenticated
  using (organization_id in (select private.user_org_ids()));

alter table public.room_template_lines enable row level security;
create policy room_template_lines_read on public.room_template_lines for select to authenticated
  using (exists (select 1 from public.room_templates t
                 where t.id = template_id
                   and (t.organization_id is null or t.organization_id in (select private.user_org_ids()))));
create policy room_template_lines_write_own on public.room_template_lines for all to authenticated
  using (exists (select 1 from public.room_templates t
                 where t.id = template_id and t.organization_id in (select private.user_org_ids())))
  with check (exists (select 1 from public.room_templates t
                      where t.id = template_id and t.organization_id in (select private.user_org_ids())));

grant select, insert, update, delete on public.room_templates, public.room_template_lines to authenticated;
revoke all on public.room_templates, public.room_template_lines from anon;

-- Add a room to a version: one line per template item, quantity = factor × size + fixed,
-- priced from the studio's current prices. Runs as the caller, so RLS applies.
create or replace function public.apply_room_template(
  p_version uuid, p_template uuid, p_size numeric, p_label text default null)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  v_org   uuid;
  v_count integer;
begin
  select organization_id into v_org from public.versions where id = p_version;
  if v_org is null then
    raise exception 'version not found';
  end if;
  if not exists (select 1 from public.room_templates where id = p_template) then
    raise exception 'template not found';
  end if;

  insert into public.line_items
    (organization_id, version_id, partida_id, quantity, unit_price, price_id, confidence, state, notes)
  select v_org, p_version, tl.partida_id,
         round(tl.factor * coalesce(p_size, 0) + tl.fixed, 3),
         cp.unit_price, cp.price_id, cp.confidence,
         case when cp.unit_price is null then 'unpriced'::public.line_state else 'priced'::public.line_state end,
         coalesce(nullif(trim(p_label), ''), t.name)
  from public.room_template_lines tl
  join public.room_templates t on t.id = tl.template_id
  left join public.current_prices(v_org) cp on cp.partida_id = tl.partida_id
  where tl.template_id = p_template
    and round(tl.factor * coalesce(p_size, 0) + tl.fixed, 3) > 0
  order by tl.sequence;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
revoke all on function public.apply_room_template(uuid, uuid, numeric, text) from public, anon;
grant execute on function public.apply_room_template(uuid, uuid, numeric, text) to authenticated;

-- ── Bid stage: one standard version until the project is won ─────────────────
create or replace function private.check_version_stage()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.versions where project_id = new.project_id)
     and (select status from public.projects where id = new.project_id) <> 'won' then
    raise exception 'Bid stage: one standard version only. Options and client changes start once the project is won.'
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;
revoke all on function private.check_version_stage() from public;
create trigger versions_stage before insert on public.versions
  for each row execute function private.check_version_stage();
"""


def migration():
    out = [SCHEMA, "\n-- ── Chapters ─────────────────────────────────────────────────────────────────"]
    out.append("insert into public.trades (region_id, code, name, cype_chapter, sequence) values")
    out.append(",\n".join(f"  ('es', {q(c)}, {q(n)}, {q(cy)}, {s})" for c, n, cy, s in C.CHAPTERS) + ";")

    out.append("\n-- ── Partidas ─────────────────────────────────────────────────────────────────")
    out.append("insert into public.partidas (region_id, code, short_description, long_description, unit, trade_id)")
    out.append("select 'es', v.code, v.short, v.spec, v.unit::public.unit, t.id from (values")
    out.append(",\n".join(f"  ({q(p['code'])}, {q(p['short'])}, {q(p['spec'])}, {q(p['unit'])})" for p in C.PARTIDAS))
    out.append(") as v(code, short, spec, unit)")
    out.append("join public.trades t on t.region_id = 'es' and t.organization_id is null and t.code = left(v.code, 3);")

    out.append("\n-- ── Room templates ───────────────────────────────────────────────────────────")
    out.append("insert into public.room_templates (region_id, code, name, size_label, description, sequence) values")
    out.append(",\n".join(f"  ('es', {q(t['code'])}, {q(t['name'])}, {q(t['size_label'])}, {q(t['description'])}, {i * 10})"
                          for i, t in enumerate(C.TEMPLATES, 1)) + ";")
    rows = []
    for t in C.TEMPLATES:
        for i, ln in enumerate(t["lines"], 1):
            rows.append(f"  ({q(t['code'])}, {q(ln['partida'])}, {ln['factor']}, {ln['fixed']}, {q(ln['note'] or None)}, {i})")
    out.append("insert into public.room_template_lines (template_id, partida_id, factor, fixed, note, sequence)")
    out.append("select rt.id, p.id, v.factor, v.fixed, v.note, v.seq from (values")
    out.append(",\n".join(rows))
    out.append(") as v(tpl, partida, factor, fixed, note, seq)")
    out.append("join public.room_templates rt on rt.region_id = 'es' and rt.organization_id is null and rt.code = v.tpl")
    out.append("join public.partidas p on p.region_id = 'es' and p.organization_id is null and p.code = v.partida;")
    return "\n".join(out) + "\n"


def prices():
    rows = [f"  ({q(p['code'])}, {p['price']}, {q(p['basis'])})" for p in C.PARTIDAS if p["price"] is not None]
    return f"""\
-- Enzyme's own prices (from Ortega y Gasset 47, P26018 REV 2). Private to the studio.
-- Run once, after the studio exists. Set the studio name below.
-- Generated by catalogue/build_sql.py.
with org as (select id, region_id from public.organizations where name = 'Enzyme' limit 1)
insert into public.prices (region_id, organization_id, partida_id, unit_price, source, confidence, priced_on, notes)
select org.region_id, org.id, p.id, v.price, 'history', 'medium', date '2026-09-01', v.basis
from org
cross join (values
{",\n".join(rows)}
) as v(code, price, basis)
join public.partidas p on p.region_id = org.region_id and p.organization_id is null and p.code = v.code;
"""


MIGRATION.write_text(migration())
PRICES.parent.mkdir(parents=True, exist_ok=True)
PRICES.write_text(prices())
print(MIGRATION)
print(PRICES)
